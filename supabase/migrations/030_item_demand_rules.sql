-- Component-demand rules: a child item needed N per unit of a PARENT item, used
-- ONLY to derive demand (Make/Trade MRP) -- NOT a production-explosion parts list.
-- Unlike item_bom_lines (which OVERRIDES a parent program in getProductionPlan and
-- would wipe the parent steel from the buy list), these rules never touch the
-- production plan; getMrpData folds them into demand, attributed to the parent jobs.
--
-- First use (owner, 2026-06-15): each safety frame needs guide shoes per the
-- "Safety Guide Shoe Demand" sheet -- 4 guide shoes/frame across SA-DC-078/079/080/081.
create table if not exists item_demand_rules (
  id uuid primary key default gen_random_uuid(),
  parent_item_id uuid not null references items(id) on delete cascade,
  child_item_id  uuid not null references items(id) on delete cascade,
  qty numeric not null check (qty > 0),
  note text,
  created_at timestamptz not null default now(),
  unique (parent_item_id, child_item_id)
);
create index if not exists idx_item_demand_rules_parent on item_demand_rules(parent_item_id);
create index if not exists idx_item_demand_rules_child on item_demand_rules(child_item_id);
alter table item_demand_rules enable row level security;
create policy "item_demand_rules all" on item_demand_rules for all to public using (true) with check (true);

